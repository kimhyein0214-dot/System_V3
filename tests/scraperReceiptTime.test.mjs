import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {normalizeCurrentDbItem} from '../src/adapters/currentDbPickingAdapter.mjs';
const html=readFileSync(new URL('../tools/sellpia_scraper.html',import.meta.url),'utf8');
const helpers=html.match(/const receiptTimeHelpers = String.raw`([\s\S]*?)`;/)?.[1];
assert.ok(helpers);
const context=vm.createContext({getSellpiaReceiptRaw:row=>row.receipt});
new vm.Script(helpers).runInContext(context);
const parse=receipt=>context.sellpiaReceiptTimeFields({receipt});
assert.equal(parse('2026-09-08 13:21:35').sellpia_received_at,'2026-09-08T13:21:35+09:00');
assert.equal(parse('2026-09-08 13:21').sellpia_received_at_precision,'minute');
assert.equal(parse('2026/9/8 오전 12:21:00').sellpia_received_at,'2026-09-08T00:21:00+09:00');
assert.equal(parse('2026년 9월 8일 오후 12:21:00').sellpia_received_at,'2026-09-08T12:21:00+09:00');
assert.equal(parse('2026-09-08T04:21:35Z').sellpia_received_at,'2026-09-08T04:21:35Z');
assert.equal(parse('2026-09-08').sellpia_received_at_precision,'date');
for(const raw of ['',null,'2026-09-08','09/08 13:00','2026-02-29 12:00','2026-09-08 24:00','2026-09-08 13:60','2026-09-08 13:00:60','2026-09-08 00:00+15:00','2026-09-08 ~ 2026-09-09'])
  assert.equal(parse(raw).sellpia_received_at,null,String(raw));
const item=normalizeCurrentDbItem({item_no:'test',receipt_date:'2026-09-08',scraped_at:'2026-09-08T08:00:00Z',...parse('2026-09-08 12:00:01')});
assert.equal(item.receiptAt,'2026-09-08T12:00:01+09:00');
assert.equal(item.receiptAtPrecision,'second');
assert.equal(normalizeCurrentDbItem({scraped_at:'2026-09-08T08:00:00Z',receipt_date:'2026-09-08'}).receiptAt,'');
const elements={'bookmarklet-link':{href:''},'code-display':{textContent:''}};
const assembled=vm.createContext({document:{getElementById:id=>elements[id]},console,encodeURIComponent});
for(const script of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) new vm.Script(script[1]).runInContext(assembled);
const code=elements['code-display'].textContent;
new vm.Script(code);
assert.equal((code.match(/\.\.\.sellpiaReceiptTimeFields\(it\)/g)||[]).length,1,'exactly one per-item storage hook');
assert.match(code,/ord_date:receiptDate,receipt_date:receiptDate,scraped_at:now/,'legacy date fields remain unchanged');
assert.match(code,/applyExistingOrderReceiptBaselines/,'original date preservation retained');
// Check the generated item object and execute its timestamp spread with synthetic locals.
const start=code.indexOf('itemRows.push({'),end=code.indexOf('});',start);
assert.ok(start>0&&end>start);
const objectCode=code.slice(start+'itemRows.push('.length,end+1);
const dataContext=vm.createContext({it:{c_item_amount:2,num:1},itemNo:'synthetic',ordNo:'synthetic',now:'2026-09-08T09:00:00Z',invNo:'',receiptDate:'2026-09-08',orderMemo:'',getSellpiaReceiptRaw:()=> '2026-09-08 13:21:35',sellpiaOutboundConfirmedDate:()=>null});
new vm.Script(helpers).runInContext(dataContext);
const storedFields=new vm.Script('({...sellpiaReceiptTimeFields(it)})').runInContext(dataContext);
assert.equal(storedFields.sellpia_received_at,'2026-09-08T13:21:35+09:00');
assert.match(objectCode,/\.\.\.sellpiaReceiptTimeFields\(it\)/);
console.log('PASS: receipt date/time parsing, KST and precision, invalid times, no scrape-time fallback, adapter and assembled bookmarklet storage hook');
